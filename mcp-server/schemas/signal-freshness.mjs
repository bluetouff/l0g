import { z } from 'zod';
import {
  SIGNAL_FRESHNESS_COVERAGE_STATUSES,
  SIGNAL_FRESHNESS_KEYS,
  SIGNAL_FRESHNESS_MISSING_FIELDS,
  SIGNAL_FRESHNESS_QUALITY_STATUSES,
  SIGNAL_FRESHNESS_SOURCE_STATUSES,
  SIGNAL_FRESHNESS_TIMELINESS_STATUSES,
} from '../../src/config/signal-freshness-contract.mjs';

export const SignalFreshnessSchema = z.object({
  key: z.enum(SIGNAL_FRESHNESS_KEYS),
  label: z.string(),
  source: z.string().url(),
  methodology: z.string().url(),
  observedAt: z.string().datetime({ offset: true }).nullable(),
  sourcePublishedAt: z.string().datetime({ offset: true }).nullable(),
  sourceCheckedAt: z.string().datetime({ offset: true }).nullable(),
  retrievedAt: z.string().datetime({ offset: true }).nullable(),
  lastAttemptAt: z.string().datetime({ offset: true }).nullable(),
  lastSuccessAt: z.string().datetime({ offset: true }).nullable(),
  computedAt: z.string().datetime({ offset: true }),
  staleAfter: z.string(),
  expiresAt: z.string().datetime({ offset: true }).nullable(),
  timelinessStatus: z.enum(SIGNAL_FRESHNESS_TIMELINESS_STATUSES),
  sourceStatus: z.enum(SIGNAL_FRESHNESS_SOURCE_STATUSES),
  qualityStatus: z.enum(SIGNAL_FRESHNESS_QUALITY_STATUSES),
  fallbackUsed: z.boolean(),
  fallbackReason: z.string().nullable(),
  warnings: z.array(z.string()),
  coverageStatus: z.enum(SIGNAL_FRESHNESS_COVERAGE_STATUSES),
  coverage: z.object({
    signalPresent: z.boolean(),
    observedAt: z.boolean(),
    sourcePublishedAt: z.boolean(),
    retrievedAt: z.boolean(),
    lastAttemptAt: z.boolean(),
    lastSuccessAt: z.boolean(),
    computedAt: z.boolean(),
    staleAfter: z.boolean(),
  }).strict(),
  missing: z.array(z.enum(SIGNAL_FRESHNESS_MISSING_FIELDS)),
  note: z.string(),
}).strict();
