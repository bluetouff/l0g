/** @param {'fr' | 'en'} lang */
function createEdition(lang) {
  const book = editionText[lang], isEn = lang === 'en';
  return {
    ...book,
    path: `${isEn ? '/en' : ''}/publications/${book.directory}/`,
    cover: `/publications/${book.directory}-cover.jpg`,
    social: `/publications/${book.directory}-og-v1.jpg`,
    editions: ['dark', 'light'].map(theme => ({
      theme,
      directory: `${book.directory}-${theme}`,
      epub: `/publications/${book.directory}-${theme}-l0g.epub`,
      id: variantIds[lang][theme],
      label: isEn ? `${theme === 'dark' ? 'Dark' : 'Light'} edition` : `Édition ${theme === 'dark' ? 'sombre' : 'claire'}`,
    })),
    chapters: chapterData.map(({ slug, titleFr, titleEn, summaryFr, summaryEn, image, figureCount }, index) => ({
      slug,
      sourceSlug: slug,
      title: isEn ? titleEn : titleFr,
      summary: isEn ? summaryEn : summaryFr,
      number: index + 1,
      figureCount,
      route: `${isEn ? '/en/analysis' : '/posts'}/${slug}/`,
      chapter: `ch${String(index + 2).padStart(3, '0')}.xhtml`,
      image,
      imageAlt: `${isEn ? 'Conceptual illustration for chapter' : 'Illustration conceptuelle du chapitre'} ${index + 1} : ${isEn ? titleEn : titleFr}`,
    })),
    glossary: glossaryByLanguage[lang],
    synthesisSources: synthesisSources[lang],
  };
}

export const debtEditions = { fr: createEdition('fr'), en: createEdition('en') };
